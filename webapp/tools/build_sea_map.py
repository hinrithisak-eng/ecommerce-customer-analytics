"""Build webapp/templates/_sea_map.svg.html from Natural Earth country shapes.

Usage:  npm pack world-atlas@2.0.2 && tar xzf world-atlas-2.0.2.tgz
        python webapp/tools/build_sea_map.py package/countries-50m.json webapp/templates/_sea_map.svg.html

The output is committed, so the app needs neither this script nor network access at runtime.
"""
import json, math, sys
OURS = {"116": "Cambodia", "764": "Thailand", "704": "Vietnam", "702": "Singapore", "458": "Malaysia", "608": "Philippines", "360": "Indonesia"}
LON0, LON1, LAT0, LAT1 = 91.0, 142.0, -12.5, 25.5
W = 1000.0
K = math.cos(math.radians(6))
H = W * (LAT1 - LAT0) / ((LON1 - LON0) * K)
def proj(lon, lat): return ((lon - LON0) / (LON1 - LON0) * W, (LAT1 - lat) / (LAT1 - LAT0) * H)

def load(path):
    t = json.load(open(path)); sc, tr = t["transform"]["scale"], t["transform"]["translate"]
    arcs = []
    for a in t["arcs"]:
        x = y = 0; pts = []
        for dx, dy in a:
            x += dx; y += dy; pts.append((x * sc[0] + tr[0], y * sc[1] + tr[1]))
        arcs.append(pts)
    def ring(idx):
        out = []
        for i in idx:
            pts = arcs[i] if i >= 0 else arcs[~i][::-1]
            out.extend(pts if not out else pts[1:])
        return out
    geoms = {}
    for g in t["objects"]["countries"]["geometries"]:
        if g["type"] == "Polygon": polys = [g["arcs"]]
        elif g["type"] == "MultiPolygon": polys = g["arcs"]
        else: continue
        geoms[g.get("id")] = (g["properties"]["name"], [[ring(r) for r in p] for p in polys])
    return geoms

def path(polys, tol):
    d = []
    for p in polys:
        for r in p:
            lons = [q[0] for q in r]; lats = [q[1] for q in r]
            if max(lons) < LON0 - 2 or min(lons) > LON1 + 2 or max(lats) < LAT0 - 2 or min(lats) > LAT1 + 2: continue
            pts = [proj(*q) for q in r]; keep = [pts[0]]
            for q in pts[1:]:
                if abs(q[0] - keep[-1][0]) + abs(q[1] - keep[-1][1]) >= tol: keep.append(q)
            if len(keep) < 3: continue
            d.append("M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in keep) + "Z")
    return "".join(d)

g50 = load(sys.argv[1])
bg, fg = [], []
for cid, (name, polys) in g50.items():
    d = path(polys, 0.6 if cid in OURS else 1.6)
    if not d: continue
    if cid in OURS: fg.append(f'<path class="c" data-country="{OURS[cid]}" d="{d}"><title>{OURS[cid]}</title></path>')
    else: bg.append(f'<path d="{d}"/>')
# Singapore is a few pixels wide: add a locator ring so it can be seen and hovered
sx, sy = proj(103.82, 1.35)
svg = (f'<svg class="sea-map" viewBox="0 0 {W:.0f} {H:.0f}" role="img" aria-label="Map of Southeast Asia shaded by net revenue">'
       f'<g class="land">{"".join(bg)}</g><g class="ours">{"".join(fg)}'
       f'<circle class="c dot" data-country="Singapore" cx="{sx:.1f}" cy="{sy:.1f}" r="7"><title>Singapore</title></circle></g></svg>')
open(sys.argv[2], "w").write("{# Generated by scripts/build_sea_map.py from Natural Earth 1:50m (world-atlas 2.0.2). Do not edit. #}\n" + svg + "\n")
print(len(svg), "bytes,", len(fg), "countries, H=", round(H))
